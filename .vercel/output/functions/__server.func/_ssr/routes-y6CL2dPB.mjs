function evaluateGuess(guess, answer) {
	const result = Array.from({ length: guess.length }, () => "absent");
	const counts = /* @__PURE__ */ new Map();
	for (let i = 0; i < guess.length; i++) if (guess[i] === answer[i]) result[i] = "correct";
	else {
		const ch = answer[i];
		if (ch) counts.set(ch, (counts.get(ch) ?? 0) + 1);
	}
	for (let i = 0; i < guess.length; i++) {
		if (result[i] === "correct") continue;
		const ch = guess[i];
		if (!ch) continue;
		const left = counts.get(ch) ?? 0;
		if (left > 0) {
			result[i] = "present";
			counts.set(ch, left - 1);
		}
	}
	return result;
}
function keyboardMarks(guesses, answer) {
	const marks = {};
	for (const guess of guesses) {
		const scored = evaluateGuess(guess, answer);
		for (let i = 0; i < guess.length; i++) {
			const ch = guess[i];
			const status = scored[i];
			if (!ch || !status) continue;
			const prev = marks[ch];
			if (!prev || RANK[status] > RANK[prev]) marks[ch] = status;
		}
	}
	return marks;
}
